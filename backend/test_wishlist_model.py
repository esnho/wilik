import unittest
from pathlib import Path
from tempfile import TemporaryDirectory

from flask import Flask
from flask_migrate import Migrate, downgrade, upgrade
from sqlalchemy import inspect
from sqlalchemy.exc import IntegrityError

from models import Gift, User, Wishlist, db


class WishlistModelTestCase(unittest.TestCase):
    def setUp(self):
        self.app = Flask(__name__)
        self.app.config.update(
            SECRET_KEY="test-secret",
            SQLALCHEMY_DATABASE_URI="sqlite:///:memory:",
            TESTING=True,
        )
        db.init_app(self.app)
        with self.app.app_context():
            db.create_all()

    def tearDown(self):
        with self.app.app_context():
            db.session.remove()
            db.drop_all()

    def create_user(self, username):
        user = User(username=username)
        db.session.add(user)
        db.session.flush()
        return user

    def test_new_list_gets_autogenerated_share_token_and_code(self):
        with self.app.app_context():
            user = self.create_user("alice")
            wishlist = Wishlist(owner_id=user.id, name="Natale")
            db.session.add(wishlist)
            db.session.commit()

            self.assertEqual(len(wishlist.share_token), 8)
            self.assertEqual(len(wishlist.code), 12)
            self.assertNotEqual(wishlist.share_token, wishlist.code)
            self.assertEqual(wishlist.owner, user)
            self.assertEqual(user.lists, [wishlist])

    def test_share_tokens_and_codes_are_unique_across_lists(self):
        with self.app.app_context():
            alice = self.create_user("alice")
            bob = self.create_user("bob")
            lists = [
                Wishlist(owner_id=alice.id, name="Natale"),
                Wishlist(owner_id=alice.id, name="Compleanno"),
                Wishlist(owner_id=bob.id, name="Natale"),
            ]
            db.session.add_all(lists)
            db.session.commit()

            self.assertEqual(len({w.share_token for w in lists}), 3)
            self.assertEqual(len({w.code for w in lists}), 3)
            self.assertEqual([w.name for w in alice.lists], ["Natale", "Compleanno"])

    def test_gift_requires_a_wishlist(self):
        with self.app.app_context():
            user = self.create_user("alice")
            wishlist = Wishlist(owner_id=user.id, name="Natale")
            db.session.add(wishlist)
            db.session.flush()

            db.session.add(Gift(owner_id=user.id, title="Senza lista"))
            with self.assertRaises(IntegrityError):
                db.session.flush()
            db.session.rollback()

    def test_gift_stays_denormalized_to_owner_and_wishlist(self):
        with self.app.app_context():
            user = self.create_user("alice")
            wishlist = Wishlist(owner_id=user.id, name="Natale")
            db.session.add(wishlist)
            db.session.flush()
            gift = Gift(owner_id=user.id, wishlist_id=wishlist.id, title="Libro")
            db.session.add(gift)
            db.session.commit()

            self.assertEqual(gift.wishlist, wishlist)
            self.assertEqual(gift.owner, user)
            self.assertEqual(wishlist.gifts, [gift])
            self.assertEqual(user.gifts, [gift])

    def test_deleting_a_list_deletes_its_gifts_only(self):
        with self.app.app_context():
            user = self.create_user("alice")
            first = Wishlist(owner_id=user.id, name="Natale")
            second = Wishlist(owner_id=user.id, name="Compleanno")
            db.session.add_all([first, second])
            db.session.flush()
            dropped = Gift(owner_id=user.id, wishlist_id=first.id, title="Sparisce")
            kept = Gift(owner_id=user.id, wishlist_id=second.id, title="Resta")
            db.session.add_all([dropped, kept])
            db.session.commit()

            db.session.delete(first)
            db.session.commit()

            self.assertIsNone(db.session.get(Gift, dropped.id))
            self.assertEqual(db.session.get(Gift, kept.id), kept)
            self.assertEqual(user.lists, [second])

    def test_deleting_a_user_deletes_lists_and_gifts(self):
        with self.app.app_context():
            user = self.create_user("alice")
            wishlist = Wishlist(owner_id=user.id, name="Natale")
            db.session.add(wishlist)
            db.session.flush()
            gift = Gift(owner_id=user.id, wishlist_id=wishlist.id, title="Libro")
            db.session.add(gift)
            db.session.commit()

            db.session.delete(user)
            db.session.commit()

            self.assertIsNone(db.session.get(Wishlist, wishlist.id))
            self.assertIsNone(db.session.get(Gift, gift.id))

    def test_list_name_is_gone_from_user(self):
        with self.app.app_context():
            user = self.create_user("alice")
            self.assertNotIn("list_name", user.to_dict())
            self.assertNotIn("list_name", user.public_dict())
            with self.assertRaises(AttributeError):
                user.list_name


def _insert_row(connection, table_name, values):
    """Insert a row at a pre-migration revision: every NOT NULL column without a
    server default gets a type-appropriate placeholder, so the caller only supplies
    the columns it cares about (and the unique ones like username/share_token)."""
    columns = inspect(db.engine).get_columns(table_name)
    for column in columns:
        # the primary key auto-assigns on insert -- filling it in would collide
        # between rows
        if (
            column["name"] in values
            or column["nullable"]
            or column["default"] is not None
            or column["primary_key"]
        ):
            continue
        column_type = str(column["type"]).upper()
        if "CHAR" in column_type or "TEXT" in column_type:
            values[column["name"]] = ""
        else:
            values[column["name"]] = 0
    placeholders = ", ".join("?" for _ in values)
    connection.exec_driver_sql(
        f"INSERT INTO {table_name} ({', '.join(values)}) VALUES ({placeholders})",
        tuple(values.values()),
    )


class WishlistMigrationTestCase(unittest.TestCase):
    def test_upgrade_creates_lists_and_moves_gifts_downgrade_reverts(self):
        migrations_directory = str(Path(__file__).parent / "migrations")
        previous_revision = "d5e6f7a8b9c0"

        with TemporaryDirectory() as temporary_directory:
            database_path = Path(temporary_directory) / "migration-test.db"
            app = Flask(__name__)
            app.config.update(
                SQLALCHEMY_DATABASE_URI=f"sqlite:///{database_path.as_posix()}",
                TESTING=True,
            )
            db.init_app(app)
            Migrate(app, db, directory=migrations_directory)

            with app.app_context():
                upgrade(directory=migrations_directory, revision=previous_revision)
                with db.engine.begin() as connection:
                    # one user with a custom list name, one without (gets the computed default)
                    _insert_row(
                        connection,
                        "user",
                        {"username": "alice", "list_name": "Natale", "share_token": "token-alice"},
                    )
                    _insert_row(
                        connection,
                        "user",
                        {"username": "bob", "list_name": None, "share_token": "token-bob"},
                    )
                    _insert_row(connection, "gift", {"owner_id": 1, "title": "Dvd alice"})
                    _insert_row(connection, "gift", {"owner_id": 1, "title": "Libro alice"})
                    _insert_row(connection, "gift", {"owner_id": 2, "title": "Libro bob"})

                upgrade(directory=migrations_directory, revision="head")

                user_columns = {column["name"] for column in inspect(db.engine).get_columns("user")}
                self.assertNotIn("list_name", user_columns)

                wishlist_columns = {
                    column["name"]: column for column in inspect(db.engine).get_columns("wishlist")
                }
                self.assertEqual(set(wishlist_columns), {"id", "owner_id", "name", "share_token", "code"})
                self.assertFalse(wishlist_columns["name"]["nullable"])
                self.assertFalse(wishlist_columns["share_token"]["nullable"])
                self.assertFalse(wishlist_columns["code"]["nullable"])

                gift_columns = {column["name"]: column for column in inspect(db.engine).get_columns("gift")}
                self.assertIn("wishlist_id", gift_columns)
                self.assertFalse(gift_columns["wishlist_id"]["nullable"])
                gift_fks = {
                    fk["constrained_columns"][0]: fk["referred_table"]
                    for fk in inspect(db.engine).get_foreign_keys("gift")
                }
                self.assertEqual(gift_fks["wishlist_id"], "wishlist")
                self.assertEqual(gift_fks["owner_id"], "user")

                with db.engine.connect() as connection:
                    lists = connection.exec_driver_sql(
                        "SELECT wishlist.owner_id, wishlist.name, wishlist.share_token, wishlist.code "
                        "FROM wishlist JOIN user ON user.id = wishlist.owner_id "
                        "ORDER BY user.username"
                    ).fetchall()
                    self.assertEqual(
                        [(row[0], row[1], row[2]) for row in lists],
                        [(1, "Natale", "token-alice"), (2, "bob's wishlist", "token-bob")],
                    )
                    self.assertTrue(all(row[3] for row in lists))
                    self.assertEqual(len({row[3] for row in lists}), 2)

                    gifts = connection.exec_driver_sql(
                        "SELECT gift.title, gift.owner_id, gift.wishlist_id, wishlist.owner_id "
                        "FROM gift JOIN wishlist ON wishlist.id = gift.wishlist_id "
                        "ORDER BY gift.title"
                    ).fetchall()
                    self.assertEqual(
                        [(row[0], row[1], row[3]) for row in gifts],
                        [("Dvd alice", 1, 1), ("Libro alice", 1, 1), ("Libro bob", 2, 2)],
                    )

                downgrade(directory=migrations_directory, revision=previous_revision)

                user_columns = {column["name"] for column in inspect(db.engine).get_columns("user")}
                self.assertIn("list_name", user_columns)
                gift_columns = {column["name"] for column in inspect(db.engine).get_columns("gift")}
                self.assertNotIn("wishlist_id", gift_columns)
                self.assertFalse(inspect(db.engine).has_table("wishlist"))

                with db.engine.connect() as connection:
                    users = connection.exec_driver_sql(
                        "SELECT username, list_name FROM user ORDER BY username"
                    ).fetchall()
                    self.assertEqual(
                        [(row[0], row[1]) for row in users],
                        [("alice", "Natale"), ("bob", "bob's wishlist")],
                    )
                    gifts = connection.exec_driver_sql(
                        "SELECT title FROM gift ORDER BY title"
                    ).fetchall()
                    self.assertEqual(
                        [row[0] for row in gifts],
                        ["Dvd alice", "Libro alice", "Libro bob"],
                    )

                db.session.remove()
                db.engine.dispose()


if __name__ == "__main__":
    unittest.main()
